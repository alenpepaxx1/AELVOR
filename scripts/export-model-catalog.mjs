import { readFileSync, writeFileSync } from "node:fs";
import { prebuiltAppConfig, ModelType } from "@mlc-ai/web-llm";

const estimates = { "Qwen2.5-0.5B-Instruct-q4f32_1-MLC": 0.4, "Qwen2.5-1.5B-Instruct-q4f32_1-MLC": 1.0, "Qwen2.5-3B-Instruct-q4f32_1-MLC": 1.9 };
const version = JSON.parse(readFileSync("node_modules/@mlc-ai/web-llm/package.json", "utf8")).version;
const models = prebuiltAppConfig.model_list.filter(record => (record.model_type ?? ModelType.LLM) === ModelType.LLM).map(record => ({
  id: record.model_id,
  name: record.model_id.replace(/-q\d+f\d+(?:_[\w]+)?-MLC(?:-1k)?$/i, "").replace(/-/g, " "),
  family: record.model_id.split("-")[0].replace(/^phi$/, "Phi"),
  precision: /q\d+f16/i.test(record.model_id) ? "FP16" : "FP32",
  memoryGB: record.vram_required_MB / 1000,
  requiredFeatures: [...new Set([...(record.required_features || []), ...(/q\d+f16/i.test(record.model_id) ? ["shader-f16"] : [])])],
  bufferBytes: record.buffer_size_required_bytes ?? null,
  contextWindow: Math.min(4096, record.overrides?.context_window_size > 0 ? record.overrides.context_window_size : 4096),
  sourceUrl: record.model,
  downloadGB: estimates[record.model_id] ?? null,
})).sort((a, b) => a.memoryGB - b.memoryGB || a.id.localeCompare(b.id));
const content = `// Copyright © 2026 Alen Pepa\n// Generated by scripts/export-model-catalog.mjs from the installed SDK.\nexport const catalogVersion = ${JSON.stringify(version)};\nexport const modelCatalogData = [\n${models.map(model => `  ${JSON.stringify(model)},`).join("\n")}\n];\n`;
if (process.argv.includes("--check")) {
  if (readFileSync("lib/model-catalog-data.ts", "utf8") !== content) throw new Error("Model catalog differs from the installed SDK. Regenerate it.");
} else writeFileSync("lib/model-catalog-data.ts", content);
console.log(`${models.length} chat models verified against WebLLM ${version}.`);
